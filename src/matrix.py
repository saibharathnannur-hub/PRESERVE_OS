"""
matrix.py -- summarise PRESERVE experiment runs into one results table.

Helper for ``run_all.sh``. It never runs an experiment. It only reads what a
run has already written to its evidence directory:

* ``baseline_result.json``: the structured baseline report (OOM count,
  kernel-identified victims, work destroyed);
* ``console.log``: the governor's log, including its SUMMARY block
  (captures/restores, PRESERVED/RESTORED lines with timings, continuity
  verdict, per-process exit events);
* ``compute_job.progress.log``: read through ``governor.load_reference_run``,
  the same extraction ``compare.py`` uses, to get the work held at the
  checkpoint.

The evidence directory is always the one the run itself reported. Nothing is
inferred from timestamps.

Subcommands::

    defaults      --scenario S                         KEY=VALUE lines for shell prompts
    custom-config --base S --compute N --hog N --delay S --out PATH
    row           --scenario S --mode M --rc N --batch K [--evidence DIR]  -> one JSON line
    table         --session FILE.jsonl --out FILE.txt [--repeat N]
    latest                                             print the newest evidence/matrix-*.txt
"""
from __future__ import annotations

import argparse
import json
import re
import shlex
import statistics
import sys
import time
from collections import Counter
from pathlib import Path

from config import PROJECT_ROOT, Config
from governor import BASELINE_RESULT, load_reference_run
from sensor import MIB

MODE_LABEL = {"baseline": "baseline", "live": "PRESERVE", "dry-run": "dry run"}
OK_RCS = {"baseline": {0, 2}, "live": {0}, "dry-run": {0}}
_REFUSED = {75: "REFUSED: another governor was running (lock held); no experiment ran",
            76: "REFUSED: setup aborted (no exclusive cgroup); no experiment ran"}
RC_MEANING = {
    "live": {1: "error, or compute_job restarted instead of resuming", 2: "no checkpoint happened",
             3: "no restore happened", 126: "sudo not available (live runs need root)", **_REFUSED},
    "baseline": {1: "error", **_REFUSED},
    "dry-run": {1: "error", 126: "sudo not available", **_REFUSED},
}
COLUMNS = ["Scenario", "Mode", "OOM kills", "Victim", "Work destroyed", "Work preserved", "Dump", "Restore",
           "Benefit"]

KILLED_RE = re.compile(r"\] (\w+) pid=(\d+) killed by SIGKILL(?: \(last reported iteration (\d+), work ([\d.]+)s\))?")
DUMP_RE = re.compile(r"PRESERVED dump pid=\d+ OK in ([\d.]+)s, image ([\d.]+)MiB")
RESTORE_RE = re.compile(r"RESTORED restore pid=\d+ OK in ([\d.]+)s")
SUMMARY_RE = re.compile(r"SUMMARY .*captures=(\d+)\s+restores=(\d+)")
# The verdict may contain spaces ("RAN CONTINUOUSLY", "CHECKPOINTED, NOT RESTORED"); it ends at " -- ".
CONTINUITY_RE = re.compile(r"compute_job continuity: (.+?) -- ")


# --------------------------------------------------------------------------
# defaults / custom-config
# --------------------------------------------------------------------------
def cmd_defaults(args: argparse.Namespace) -> int:
    cfg = Config(None, args.scenario)
    mem_max = cfg.get_size("cgroup", "memory_max")
    values = {
        "COMPUTE": cfg.get_str("workloads", "compute_working_set_mb"),
        "HOG": cfg.get_str("workloads", "hog_target_mb"),
        "DELAY": cfg.get_str("workloads", "hog_start_delay_s"),
        "MEMMAX_MIB": "0" if mem_max is None else str(mem_max // MIB),
    }
    for k, v in values.items():
        print(f"{k}={shlex.quote(v)}")
    return 0


def cmd_custom_config(args: argparse.Namespace) -> int:
    """Write a copy of preserve.conf plus a [scenario.custom] section. preserve.conf is untouched."""
    out = Path(args.out).resolve()
    if out.parent != PROJECT_ROOT:
        print(f"custom config must live in the project root {PROJECT_ROOT} so relative paths resolve")
        return 1
    base = Config(None, args.base)
    overrides = dict(base.overrides)
    overrides[("workloads", "compute_working_set_mb")] = str(args.compute)
    overrides[("workloads", "hog_target_mb")] = str(args.hog)
    overrides[("workloads", "hog_start_delay_s")] = str(args.delay)
    overrides[("baseline", "reference_live_run")] = ""
    lines = ["", "# ---- generated by run_all.sh for one custom run; preserve.conf itself is unchanged ----",
             "[scenario.custom]",
             f"description = Custom run from run_all.sh based on scenario {args.base}: "
             f"compute_working_set_mb={args.compute} hog_target_mb={args.hog} hog_start_delay_s={args.delay}"]
    lines += [f"{s}.{k} = {v}" for (s, k), v in sorted(overrides.items())]
    out.write_text((PROJECT_ROOT / "preserve.conf").read_text() + "\n".join(lines) + "\n")
    Config(out, "custom")  # validate: every override must name a real key
    return 0


# --------------------------------------------------------------------------
# row: extract one run's numbers from its evidence directory
# --------------------------------------------------------------------------
def build_row(scenario: str, mode: str, rc: int, batch: int, evidence: Path | None) -> dict:
    row: dict = {"scenario": scenario, "mode": mode, "rc": rc, "batch": batch,
                 "evidence": str(evidence) if evidence else None, "failed": False, "reason": "",
                 "has_data": False, "oom_kills": None, "victim": None, "destroyed_s": None,
                 "destroyed_partial": False, "preserved_s": None, "dump_s": None, "image_mib": None,
                 "restore_s": None}
    if rc not in OK_RCS.get(mode, {0}):
        row["failed"] = True
        row["reason"] = RC_MEANING.get(mode, {}).get(rc, f"exit code {rc}")
    if evidence is None or not (evidence / "console.log").exists():
        row["failed"] = True
        row["reason"] = row["reason"] or "run reported no evidence folder"
        return row
    # A FAILED marker written by run_demo.sh is authoritative: the run did not
    # complete, so its cell must never show a stale or partial value.
    if (evidence / "FAILED").exists():
        row["failed"] = True
        marker = (evidence / "FAILED").read_text(errors="replace").splitlines()
        row["reason"] = row["reason"] or (marker[0] if marker else "run marked FAILED")
        return row
    console = (evidence / "console.log").read_text(errors="replace")
    if "SUMMARY" not in console:
        row["failed"] = True
        row["reason"] = row["reason"] or "governor did not reach its summary (crash?)"
        return row
    row["has_data"] = True

    if mode == "baseline":
        try:
            result = json.loads((evidence / BASELINE_RESULT).read_text())
        except (OSError, ValueError):
            row["failed"], row["reason"] = True, f"missing or unreadable {BASELINE_RESULT}"
            return row
        row["oom_kills"] = result.get("oom_kill", 0)
        victims = result.get("victims", [])
        row["victim"] = ", ".join(sorted({v.get("role", "?") for v in victims})) or "none"
        row["destroyed_s"] = round(sum(v.get("work_lost_s", 0.0) for v in victims), 2)
        return row

    kills = [int(x) for x in re.findall(r"oom_kill=(\d+)", console)]
    row["oom_kills"] = max(kills) if kills else 0
    victims: dict[str, tuple[str, float | None]] = {}
    for m in KILLED_RE.finditer(console):
        victims[m[2]] = (m[1], float(m[4]) if m[4] else None)  # dedupe: events repeat in SUMMARY
    row["victim"] = ", ".join(sorted({role for role, _ in victims.values()})) or "none"
    row["destroyed_s"] = round(sum(w or 0.0 for _, w in victims.values()), 2)
    row["destroyed_partial"] = any(w is None for _, w in victims.values())

    if mode == "live":
        dump, restore = DUMP_RE.search(console), RESTORE_RE.search(console)
        summary, continuity = SUMMARY_RE.search(console), CONTINUITY_RE.search(console)
        if dump:
            row["dump_s"], row["image_mib"] = float(dump[1]), float(dump[2])
        if restore:
            row["restore_s"] = float(restore[1])
        resumed = continuity is not None and continuity[1] == "RESUMED"
        if summary and int(summary[1]) > 0 and int(summary[2]) > 0 and resumed:
            ref = load_reference_run(evidence)
            row["preserved_s"] = ref.get("before_work_s")
        else:
            row["preserved_s"] = 0.0
    return row


def cmd_row(args: argparse.Namespace) -> int:
    evidence = Path(args.evidence) if args.evidence else None
    print(json.dumps(build_row(args.scenario, args.mode, args.rc, args.batch, evidence)))
    return 0


# --------------------------------------------------------------------------
# table
# --------------------------------------------------------------------------
def _agg(values: list, unit: str = "s") -> str:
    vals = [v for v in values if v is not None]
    if not vals:
        return "n/a"
    fmt = (lambda x: f"{x:.2f}{unit}") if unit else (lambda x: f"{x:g}")
    if len(vals) == 1:
        return fmt(vals[0])
    return f"{fmt(statistics.median(vals))} [{fmt(min(vals))}-{fmt(max(vals))}]"


def _kills_compute(row: dict) -> bool:
    return "compute" in (row.get("victim") or "")


def benefit(first: dict, data: list[dict], session: list[dict]) -> str:
    """Did PRESERVE save work that the kernel would actually have destroyed?

    Compares a PRESERVE row with the successful baseline runs of the *same
    scenario in the same session*: work preserved only counts as a benefit if
    the baseline's OOM killer chose compute_job.
    """
    if first["mode"] != "live":
        return "n/a"
    baselines = [r for r in session if r["scenario"] == first["scenario"]
                 and r["mode"] == "baseline" and not r["failed"]]
    if not baselines:
        return "unknown (no baseline this session)"
    at_risk = [r for r in baselines if _kills_compute(r)]
    if not at_risk:
        return "none"  # the kernel never picked compute_job: the preserved work was never at risk
    saved = [r for r in data if not _kills_compute(r) and (r["preserved_s"] or 0) > 0]
    if not saved:
        return "no (compute_job lost)" if any(_kills_compute(r) for r in data) else "no (not checkpointed)"
    cell = f"yes (+{statistics.median(r['preserved_s'] for r in saved):.2f}s)"
    if len(at_risk) < len(baselines):
        cell += f" [baseline killed compute_job in {len(at_risk)}/{len(baselines)}]"
    return cell


def group_cells(rows: list[dict], session: list[dict]) -> list[str]:
    first = rows[0]
    n, failed = len(rows), [r for r in rows if r["failed"]]
    ok = [r for r in rows if not r["failed"]]
    mode = MODE_LABEL.get(first["mode"], first["mode"]) + (f" x{n}" if n > 1 else "")
    if failed:
        mode += " FAILED" if not ok else f" ({len(failed)} FAILED)"
    data = ok or [r for r in rows if r["has_data"]]
    if not data:
        return [first["scenario"], mode] + ["FAILED"] * (len(COLUMNS) - 2)

    victims = Counter(r["victim"] for r in data)
    victim, count = victims.most_common(1)[0]
    victim_cell = victim if len(data) == 1 else f"{victim} ({count}/{len(data)})"
    destroyed = _agg([r["destroyed_s"] for r in data])
    if any(r["destroyed_partial"] for r in data):
        destroyed += " +?"  # a victim declared no work (e.g. the hog)
    is_live = first["mode"] == "live"
    return [
        first["scenario"], mode,
        _agg([r["oom_kills"] for r in data], unit=""),
        victim_cell,
        destroyed,
        _agg([r["preserved_s"] for r in data]) if is_live else "n/a",
        _agg([r["dump_s"] for r in data]) if is_live else "n/a",
        _agg([r["restore_s"] for r in data]) if is_live else "n/a",
        benefit(first, data, session),
    ]


def headline(rows: list[dict]) -> str:
    def pick(mode: str, key: str) -> list[float]:
        return [r[key] for r in rows if r["scenario"] == "B" and r["mode"] == mode
                and not r["failed"] and r[key] is not None]

    destroyed, preserved = pick("baseline", "destroyed_s"), pick("live", "preserved_s")
    if not destroyed or not preserved:
        missing = [name for name, v in (("Scenario B baseline", destroyed), ("Scenario B PRESERVE", preserved))
                   if not v]
        return f"Headline: needs a successful {' and '.join(missing)} run in this session."
    d, p = statistics.median(destroyed), statistics.median(preserved)
    suffix = f" (medians, n={len(destroyed)} / n={len(preserved)})" if len(destroyed) > 1 or len(preserved) > 1 else ""
    return (f"Headline (Scenario B): the kernel OOM killer destroyed {d:.2f}s of compute_job's work; "
            f"PRESERVE checkpointed {p:.2f}s of work and resumed it with nothing lost{suffix}.")


def render(rows: list[dict], repeat: int, arena_lines: list[str] | None = None) -> str:
    batches: dict[int, list[dict]] = {}
    for r in rows:
        batches.setdefault(r["batch"], []).append(r)
    table = [COLUMNS] + [group_cells(b, rows) for b in batches.values()]
    widths = [max(len(str(line[i])) for line in table) for i in range(len(COLUMNS))]
    sep = "-+-".join("-" * w for w in widths)
    out = [f"PRESERVE experiment matrix -- {time.strftime('%Y-%m-%d %H:%M:%S')}  (repeat={repeat})"]
    if arena_lines:
        out.append("Arena at batch start (reaped before each batch):")
        out += [f"  {line}" for line in arena_lines]
    out.append("")
    out.append(" | ".join(str(c).ljust(w) for c, w in zip(table[0], widths)))
    out.append(sep)
    out += [" | ".join(str(c).ljust(w) for c, w in zip(line, widths)) for line in table[1:]]
    out += ["", headline(rows), "",
            "Work destroyed = accumulated work of processes the kernel killed (cost-model R at death).",
            "Work preserved = compute_job work held at the checkpoint and resumed after restore.",
            "Benefit        = PRESERVE row vs the same scenario's baseline in this session: yes (+Xs) if the "
            "baseline OOM killer killed compute_job and PRESERVE kept it (X = work preserved); none if the "
            "baseline never killed compute_job, so the preserved work was never at risk; n/a for baseline "
            "and dry-run rows.",
            "With repeats: median [min-max]."]
    out += ["", "Runs and evidence:"]
    for i, r in enumerate(rows, 1):
        status = f"FAILED: {r['reason']}" if r["failed"] else "ok"
        out.append(f"  {i:2d}. {r['scenario']:<16} {MODE_LABEL.get(r['mode'], r['mode']):<9} rc={r['rc']:<3} "
                   f"{status:<12} {r['evidence'] or '-'}")
    return "\n".join(out) + "\n"


def cmd_table(args: argparse.Namespace) -> int:
    session = Path(args.session)
    rows = [json.loads(line) for line in session.read_text().splitlines() if line.strip()] \
        if session.exists() else []
    if not rows:
        print("(no runs completed in this session yet)")
        return 0
    arena_lines = []
    if args.arena_log and Path(args.arena_log).exists():
        arena_lines = [ln for ln in Path(args.arena_log).read_text().splitlines() if ln.strip()]
    text = render(rows, args.repeat, arena_lines)
    Path(args.out).write_text(text)
    print(text, end="")
    print(f"saved to {args.out}")
    return 0


def cmd_latest(_args: argparse.Namespace) -> int:
    files = sorted((PROJECT_ROOT / "evidence").glob("matrix-*.txt"), key=lambda p: p.stat().st_mtime)
    if not files:
        print("no saved results table yet (evidence/matrix-*.txt)")
        return 0
    print(f"# {files[-1]}")
    print(files[-1].read_text(), end="")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description="Summarise PRESERVE runs (helper for run_all.sh).")
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("defaults")
    p.add_argument("--scenario", default=None)
    p = sub.add_parser("custom-config")
    p.add_argument("--base", required=True)
    p.add_argument("--compute", type=int, required=True)
    p.add_argument("--hog", type=int, required=True)
    p.add_argument("--delay", type=float, required=True)
    p.add_argument("--out", required=True)
    p = sub.add_parser("row")
    p.add_argument("--scenario", required=True)
    p.add_argument("--mode", required=True, choices=sorted(MODE_LABEL))
    p.add_argument("--rc", type=int, required=True)
    p.add_argument("--batch", type=int, required=True)
    p.add_argument("--evidence", default=None)
    p = sub.add_parser("table")
    p.add_argument("--session", required=True)
    p.add_argument("--out", required=True)
    p.add_argument("--repeat", type=int, default=1)
    p.add_argument("--arena-log", default=None, help="file of per-batch 'ARENA:' lines for the header")
    sub.add_parser("latest")
    args = ap.parse_args()
    return {"defaults": cmd_defaults, "custom-config": cmd_custom_config, "row": cmd_row,
            "table": cmd_table, "latest": cmd_latest}[args.cmd](args)


if __name__ == "__main__":
    sys.exit(main())
